class ProvinceStats {
  final String provinceName;
  final double distanceKm;
  final double traveledKm;
  final int tripCount;
  final int waypointCount;
  final int rank;

  ProvinceStats({
    required this.provinceName,
    required this.distanceKm,
    double? traveledKm,
    required this.tripCount,
    required this.waypointCount,
    this.rank = 0,
  }) : traveledKm = traveledKm ?? distanceKm;

  String get tierName {
    final effectiveKm = distanceKm > 0 ? distanceKm : traveledKm;
    if (effectiveKm > 100) return 'Khám Phá Toàn Diện';
    if (effectiveKm > 40) return 'Khám Phá Sâu';
    if (effectiveKm > 10) return 'Đã Ghé Thăm';
    return 'Mới Đặt Chân';
  }
}

