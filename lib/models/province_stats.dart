  static List<_ProvinceSeed>? _seedCache;
  static final Map<int, String> _cellCache = {};

  static List<_ProvinceSeed> get _allSeeds {
    final cached = _seedCache;
    if (cached != null) return cached;
    final list = <_ProvinceSeed>[];
    _seeds.forEach((name, flat) {
      for (int i = 0; i + 1 < flat.length; i += 2) {
        list.add(_ProvinceSeed(name, flat[i], flat[i + 1]));
      }
    });
    _seedCache = list;
    return list;
  }

  /// Whether coordinates fall inside the approximate Vietnam bounding box
  /// (including offshore islands such as Côn Đảo & Phú Quốc).
  static bool isInsideVietnam(double lat, double lng) {
    return lat >= 8.0 && lat <= 23.6 && lng >= 102.0 && lng <= 110.0;
  }

  /// Resolves a coordinate to one of the 63 provinces fully offline using the
  /// nearest administrative reference point. Results are cached per ~1km cell.
  static String provinceForCoordinate(double lat, double lng) {
    final cellLat = (lat * 100).floor();
    final cellLng = (lng * 100).floor();
    final key = (cellLat + 100000) * 1000000 + (cellLng + 100000);
    final hit = _cellCache[key];
    if (hit != null) return hit;

    // Evaluate at the cell centre so the cache is deterministic.
    final cLat = (cellLat + 0.5) / 100.0;
    final cLng = (cellLng + 0.5) / 100.0;
    final cosLat = _cosDeg(cLat);

    String best = 'TP. Hồ Chí Minh';
    double bestDist = double.infinity;
    for (final seed in _allSeeds) {
      final dLat = seed.lat - cLat;
      final dLng = (seed.lng - cLng) * cosLat;
      final d = dLat * dLat + dLng * dLng;
      if (d < bestDist) {
        bestDist = d;
        best = seed.province;
      }
    }

    if (_cellCache.length > 200000) _cellCache.clear();
    _cellCache[key] = best;
    return best;
  }

  static double _cosDeg(double deg) {
    // Small Taylor-free helper avoiding dart:math import in the model layer.
    final rad = deg * 3.141592653589793 / 180.0;
    final x2 = rad * rad;
    return 1 - x2 / 2 + x2 * x2 / 24 - x2 * x2 * x2 / 720;
  }

  /// Text-based fallback: returns the province mentioned LAST in the address
  /// (Vietnamese addresses end with the province), accent-insensitive.
  static String? matchProvinceFromText(String? address) {
    if (address == null || address.trim().isEmpty) return null;
    final text = _stripAccents(address.toLowerCase());

    String? best;
    int bestPos = -1;
    int bestLen = 0;

    void consider(String keyword, String province) {
      final pos = text.lastIndexOf(keyword);
      if (pos < 0) return;
      if (pos > bestPos || (pos == bestPos && keyword.length > bestLen)) {
        bestPos = pos;
        bestLen = keyword.length;
        best = province;
      }
    }

    for (final p in allProvinces) {
      consider(_stripAccents(p.toLowerCase()), p);
    }
    consider('ho chi minh', 'TP. Hồ Chí Minh');
    consider('sai gon', 'TP. Hồ Chí Minh');
    consider('tphcm', 'TP. Hồ Chí Minh');
    consider('ha noi', 'Hà Nội');
    consider('da nang', 'Đà Nẵng');
    consider('vung tau', 'Bà Rịa - Vũng Tàu');
    consider('da lat', 'Lâm Đồng');
    consider('nha trang', 'Khánh Hoà');
    return best;
  }

  /// Matches a location to one of the 63 provinces.
  ///
  /// Coordinates are always preferred (accurate per-point offline lookup).
  /// The address text is only used when coordinates are missing/invalid,
  /// because reverse-geocoders now return post-2025 merged province names.
  static String matchProvince(double lat, double lng, String? address) {
    if (isInsideVietnam(lat, lng)) {
      return provinceForCoordinate(lat, lng);
    }
    final fromText = matchProvinceFromText(address);
    if (fromText != null) return fromText;
    if (lat == 0.0 && lng == 0.0) return 'TP. Hồ Chí Minh';
    return provinceForCoordinate(lat, lng);
  }

  static String _stripAccents(String input) {
    const vietnamese =
        'àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ';
    const latin =
        'aaaaaaaaaaaaaaaaaeeeeeeeeeeeiiiiiooooooooooooooooouuuuuuuuuuuyyyyyd';
    final buffer = StringBuffer();
    for (final rune in input.runes) {
      final ch = String.fromCharCode(rune);
      final idx = vietnamese.indexOf(ch);
      buffer.write(idx >= 0 ? latin[idx] : ch);
    }
    return buffer.toString();
  }
}

